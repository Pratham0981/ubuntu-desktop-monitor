#!/usr/bin/env bash
# Install the dashboard widget for the current user and start it at login.
#
# Everything lives under $HOME, so this needs no root. Re-running it replaces
# the previous copy and leaves an identical result.
set -euo pipefail

source_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
data_dir="${XDG_DATA_HOME:-$HOME/.local/share}/dashboard-widget"
bin_dir="$HOME/.local/bin"
autostart_dir="${XDG_CONFIG_HOME:-$HOME/.config}/autostart"
launcher="$bin_dir/dashboard-widget"
python="${PYTHON:-python3}"

if ! command -v "$python" >/dev/null 2>&1; then
    echo "install.sh: $python not found; run with PYTHON=/path/to/python3" >&2
    exit 1
fi

if ! "$python" -c "import gi, psutil" >/dev/null 2>&1; then
    echo "install.sh: $python cannot import gi and psutil" >&2
    echo "  the distro packages python3-gi and python3-psutil provide both" >&2
    exit 1
fi

mkdir -p "$data_dir" "$bin_dir" "$autostart_dir"

# Replace the packaged copy so removed modules do not linger.
rm -rf "$data_dir/dashboard"
cp -a "$source_dir/dashboard" "$data_dir/dashboard"
find "$data_dir" -name '__pycache__' -type d -prune -exec rm -rf {} +

cat > "$launcher" <<LAUNCHER
#!/bin/sh
# Generated by dashboard-widget install.sh. Re-run install.sh to update.
export GDK_BACKEND="\${GDK_BACKEND:-x11}"
export PYTHONPATH="$data_dir\${PYTHONPATH:+:\$PYTHONPATH}"
exec "$python" -m dashboard "\$@"
LAUNCHER
chmod 0755 "$launcher"

cat > "$autostart_dir/dashboard-widget.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=System Dashboard
Comment=CPU, RAM, disk and temperature at a glance
Exec=$launcher
Terminal=false
NoDisplay=true
StartupNotify=false
X-GNOME-Autostart-enabled=true
DESKTOP
chmod 0644 "$autostart_dir/dashboard-widget.desktop"

echo "Installed to $data_dir"
echo "Launcher:  $launcher"
echo "Autostart: $autostart_dir/dashboard-widget.desktop (starts at next login)"
echo "Run now:   $launcher"
